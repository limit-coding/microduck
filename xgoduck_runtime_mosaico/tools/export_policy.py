"""Export the exact supported ONNX graph to immutable float32 C weights."""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np
import onnx
from onnx import numpy_helper, helper

def export(model, dest):
    m = onnx.load(model)
    onnx.checker.check_model(m)
    g = m.graph
    tensors = {t.name: numpy_helper.to_array(t) for t in g.initializer}
    expected = ['Sub', 'Div', 'Gemm', 'Elu', 'Gemm', 'Elu', 'Gemm', 'Elu', 'Gemm']
    if [n.op_type for n in g.node] != expected:
        raise ValueError('Unsupported graph; export requires normalizer + 4 Gemm / 3 ELU layers')
    dims = lambda v: [d.dim_value for d in v.type.tensor_type.shape.dim]
    if len(g.input)!=1 or len(g.output)!=1 or dims(g.input[0])!=[1,61] or dims(g.output[0])!=[1,14]:
        raise ValueError('Expected float32 [1,61] -> [1,14]')
    if g.input[0].type.tensor_type.elem_type != onnx.TensorProto.FLOAT or g.output[0].type.tensor_type.elem_type != onnx.TensorProto.FLOAT:
        raise ValueError('Expected float32 I/O')
    last=g.input[0].name
    arrays=[]
    for i,n in enumerate(g.node):
        if n.domain not in ('','ai.onnx') or n.input[0]!=last or len(n.output)!=1:
            raise ValueError('Unsupported graph connectivity/domain')
        attrs={a.name:helper.get_attribute_value(a) for a in n.attribute}
        if n.op_type in ('Sub','Div'):
            if len(n.input)!=2 or attrs: raise ValueError('Unsupported normalizer')
            arrays.append(('MEAN' if i==0 else 'DIV', tensors[n.input[1]], (1,61)))
        elif n.op_type=='Gemm':
            if len(n.input)!=3 or attrs.get('transA',0)!=0 or attrs.get('transB',0)!=1 or attrs.get('alpha',1)!=1 or attrs.get('beta',1)!=1 or set(attrs)-{'transA','transB','alpha','beta'}:
                raise ValueError('Unsupported Gemm attributes')
            layer=(i-2)//2
            ni,no=[61,512,256,128][layer],[512,256,128,14][layer]
            arrays += [(f'W{layer}',tensors[n.input[1]],(no,ni)),(f'B{layer}',tensors[n.input[2]],(no,))]
        elif len(n.input)!=1 or attrs.get('alpha',1)!=1 or set(attrs)-{'alpha'}:
            raise ValueError('Unsupported ELU')
        last=n.output[0]
    if last!=g.output[0].name: raise ValueError('Unsupported output')
    dest.mkdir(parents=True,exist_ok=True)
    offsets=[]; flat=[]; count=0
    for name,a,shape in arrays:
        if a.shape!=shape or a.dtype!=np.float32 or not np.isfinite(a).all():
            raise ValueError(f'Invalid tensor {name}: {a.shape}/{a.dtype}')
        if name=='DIV' and (a==0).any(): raise ValueError('Zero divisor')
        offsets.append(f'#define POLICY_{name} {count}')
        flat.extend(a.ravel()); count+=a.size
    sha=hashlib.sha256(Path(model).read_bytes()).hexdigest()
    (dest/'policy_layout.h').write_text('#pragma once\n'+'\n'.join(offsets)+f'\n#define POLICY_FLOATS {count}\n',encoding='utf-8')
    import onnxruntime as ort
    session=ort.InferenceSession(str(model),providers=['CPUExecutionProvider'])
    ref=session.run(None,{g.input[0].name:np.zeros((1,61),np.float32)})[0].ravel()
    fmt=lambda v: f'{float(v):.9e}f'
    with (dest/'policy_data.c').open('w',encoding='utf-8',newline='\n') as f:
        f.write('/* Generated by tools/export_policy.py; source SHA256 '+sha+' */\n#include "policy.h"\nconst float policy_weights[] = {\n')
        for i in range(0,count,8): f.write(','.join(map(fmt,flat[i:i+8]))+',\n')
        f.write('};\n')
    (dest/'policy_reference.h').write_text('#pragma once\nstatic const float policy_zero_reference[14]={'+','.join(map(fmt,ref))+'};\n',encoding='utf-8')
    manifest={'model':Path(model).name,'sha256':sha,'input':[1,61],'output':[1,14],'architecture':[61,512,256,128,14],'activation':'ELU alpha=1','weight_floats':count,'weight_bytes':count*4}
    (dest/'policy_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(manifest))

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('model',type=Path);ap.add_argument('--out',type=Path,default=Path(__file__).resolve().parents[1]/'main')
    a=ap.parse_args();export(a.model,a.out)
